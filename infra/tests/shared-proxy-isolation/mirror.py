#!/usr/bin/env python3
"""
NEM-018 — build a LOCAL stand-in stack from a real compose file.

Reads the resolved `docker compose config --format json` and writes a compose
file that keeps each service's real networks and Traefik labels but replaces the
application with a small identity responder. Local testing only.

TLS is kept: `tls.certresolver` labels become `tls=true` (Traefik's self-signed
certificate), so the routers and the https redirect regexes behave as in
production. External network names get a prefix that preserves Docker's
network-name sort order relative to the project networks.

Usage: mirror.py <config.json> <who-prefix> <net-prefix> <out.yml>
         [--rename OLD=NEW] [--alias PREFIX] [--rewrite-host HOST]
"""
import argparse
import json

# Identity responder. Answers "<WHO>" on every port the real services use,
# records bearer tokens it receives (GET /__tokens) and accepts websocket
# upgrades. REWRITE_TO reproduces services/web/next.config.js `rewrites()`:
# /api/:path* -> <REWRITE_TO>/:path*, forwarding method, headers and body.
RESPONDER = r"""
const h=require('http');const who=process.env.WHO,to=process.env.REWRITE_TO;const seen=[];
const srv=(q,r)=>{
  const a=q.headers.authorization;if(a)seen.push(a);
  if(q.url==='/__tokens')return r.end(JSON.stringify(seen));
  if(to&&q.url.startsWith('/api/')){
    const u=new URL(to+q.url.slice(4));
    const p=h.request(u,{method:q.method,headers:{...q.headers,host:u.host},timeout:2000},x=>{r.writeHead(x.statusCode,x.headers);x.pipe(r)});
    p.on('timeout',()=>p.destroy());
    p.on('error',()=>{r.statusCode=500;r.end('rewrite-failed')});
    return q.pipe(p);
  }
  r.setHeader('x-seen-path',q.url);r.end(who);
};
for(const p of [3000,4000,5000,5432,6379,7700,8000,8080,9000,9001,9090,9100]){
  const s=h.createServer(srv);
  s.on('upgrade',(q,c)=>{c.end('HTTP/1.1 101 Switching Protocols\r\nConnection: Upgrade\r\nUpgrade: websocket\r\nx-who: '+who+'\r\n\r\n')});
  s.listen(p);
}
"""


def esc(v):
    return v.replace('$$', '$').replace('$', '$$')


def main():
    ap = argparse.ArgumentParser()
    for a in ('config', 'who', 'prefix', 'out'):
        ap.add_argument(a)
    ap.add_argument('--rename', default='')
    ap.add_argument('--alias', default='')
    ap.add_argument('--rewrite-host', default='')
    o = ap.parse_args()
    cfg = json.load(open(o.config))
    old, new = o.rename.split('=') if o.rename else ('', '')
    ext = lambda n: new if n == old else n
    lines = ['# GENERATED by infra/tests/shared-proxy-isolation/mirror.py — local test only', 'services:']
    for name, svc in cfg['services'].items():
        env = {'WHO': f'{o.who}-{name}'}
        if o.rewrite_host and name == 'web':
            env['REWRITE_TO'] = f'http://{o.rewrite_host}:4000'
        lines += [f'  {name}:', '    image: node:20-alpine',
                  f'    command: ["node", "-e", {json.dumps(RESPONDER)}]',
                  f'    environment: {json.dumps(env)}']
        labels = []
        for k, v in sorted((svc.get('labels') or {}).items()):
            if not k.startswith('traefik.'):
                continue
            if k.endswith('.tls.certresolver'):
                k, v = k.replace('.tls.certresolver', '.tls'), 'true'
            if k == 'traefik.docker.network':
                v = o.prefix + ext(v)
            labels.append(f'{k}={esc(v)}')
        if labels:
            lines.append('    labels:')
            lines += [f'      - {json.dumps(l)}' for l in labels]
        lines.append('    networks:')
        for net in (svc.get('networks') or {}):
            key = ext(net)
            if o.alias and labels:
                lines.append(f'      {key}: {{ aliases: ["{o.alias}-{name}"] }}')
            else:
                lines.append(f'      {key}: {{}}')
    lines.append('networks:')
    for key, n in cfg.get('networks', {}).items():
        if n.get('external'):
            lines.append(f'  {ext(key)}: {{ external: true, name: {o.prefix}{ext(n.get("name", key))} }}')
        else:
            lines.append(f'  {key}: {{ driver: bridge }}')
    open(o.out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
