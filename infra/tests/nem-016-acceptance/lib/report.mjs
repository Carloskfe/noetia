// Renders the acceptance report and the generated coverage matrix.
import { MATRIX, overallVerdict, STATUSES, testStatus } from './matrix.mjs';

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const AUTOMATION = (t) => {
  const kinds = new Set(t.checks.map((c) => c.kind));
  if (kinds.has('local')) return 'Local only';
  if (kinds.has('api') && kinds.size === 1) return 'Automated';
  if (kinds.has('api') || kinds.has('db')) return 'Partly automated';
  return kinds.has('manual') ? 'Manual' : 'Operator';
};

export const CLASSIFICATION = `| Status | Meaning |
|---|---|
| **PASS** | Executed; the expected result was observed |
| **FAIL** | Executed; the result differed from what was expected |
| **BLOCKED** | Can't be executed yet: approval or a prerequisite is missing, or the sequence can no longer be replayed |
| **NOT RUN** | Could be executed but hasn't been, or the result was inconclusive |

A test's status comes from its checks: any FAIL makes it FAIL, otherwise any BLOCKED makes it BLOCKED, otherwise any NOT RUN makes it NOT RUN. It's PASS only if every check passed.

The verdict is **ACCEPTED** only if every required test passed. It's **REJECTED** if any test failed, including an optional one. Anything else is **INCOMPLETE**. Optional tests (A8b, A14b) and local-only evidence (X7) can't produce ACCEPTED.`;

export function renderReport({ state = { results: {} }, meta = {}, template = false } = {}) {
  const r = state.results ?? {};
  const counts = Object.fromEntries(STATUSES.map((s) => [s, 0]));
  for (const t of MATRIX) counts[testStatus(t, r)]++;
  const blank = '____';
  const out = [];
  out.push(`# NEM-016 acceptance report${template ? ' (template)' : ''}`, '');
  out.push(`| Field | Value |\n|---|---|`);
  out.push(`| Target | ${esc(meta.target ?? blank)} |`);
  out.push(`| Deployed commit | ${esc(meta.sha ?? blank)} |`);
  out.push(`| Run ID | ${esc(state.runId ?? blank)} |`);
  out.push(`| Generated | ${esc(meta.generated ?? blank)} |`);
  out.push(`| Operator | ${blank} |`);
  out.push(`| Product Owner authorization (reference) | ${blank} |`);
  out.push(`| Approved disruptive tests | ${esc(meta.approved ?? blank)} |`, '');
  out.push(`## Verdict: ${template ? blank : overallVerdict(r)}`, '');
  out.push(`| PASS | FAIL | BLOCKED | NOT RUN |\n|---|---|---|---|\n| ${counts.PASS} | ${counts.FAIL} | ${counts.BLOCKED} | ${counts['NOT RUN']} |`, '');
  out.push('## Classification', '', CLASSIFICATION, '');
  out.push('## Summary', '', '| Test | Area | Requirement | Status |\n|---|---|---|---|');
  for (const t of MATRIX) {
    const flags = [t.optional ? 'optional' : '', t.localOnly ? 'local only' : ''].filter(Boolean).join(', ');
    out.push(`| ${t.id} | ${esc(t.area)}${flags && !t.area.includes(flags) ? ` (${flags})` : ''} | ${esc(t.requirement.join(', '))} | ${testStatus(t, r)} |`);
  }
  out.push('', '## Checks', '', '| Check | Kind | Expected | Status | Evidence |\n|---|---|---|---|---|');
  for (const t of MATRIX) for (const c of t.checks) {
    const res = r[c.id];
    out.push(`| ${c.id} | ${c.kind} | ${esc(c.desc)} | ${res?.status ?? 'NOT RUN'} | ${esc(res?.detail ?? '')} |`);
  }
  out.push('', '## Data changes and clean-up', '');
  out.push('- Accounts created: ' + (Object.keys(state.users ?? {}).length || blank));
  out.push('- Shares recorded: ' + (Object.keys(state.shares ?? {}).length || blank));
  out.push('- Fixture book: ' + (state.book ? `${state.book.id}${state.book.deleted ? ' (deleted)' : ''}` : blank));
  out.push(`- Clean-up: ${esc(state.cleanup?.summary ?? blank)}`);
  out.push('- Left behind: the fixture text object, A19\'s `shareCount` +1, rate-limit keys until they expire', '');
  out.push('## Findings and deviations', '', blank, '', '## Sign-off', '', `- Operator: ${blank}`, `- Product Owner: ${blank}`, '');
  return out.join('\n');
}

export function renderCoverage() {
  const out = ['# NEM-016 acceptance coverage', '', '_Generated by `acceptance.mjs coverage` from `lib/matrix.mjs`. Don\'t edit by hand._', ''];
  out.push('## By test', '', '| Test | Area | Requirement | Source | Automation | api / db / operator / manual / local | Data | PO approval |\n|---|---|---|---|---|---|---|---|');
  for (const t of MATRIX) {
    const n = (k) => t.checks.filter((c) => c.kind === k).length;
    out.push(`| ${t.id} | ${esc(t.area)} | ${esc(t.requirement.join(', '))} | ${esc(t.source)} | ${AUTOMATION(t)} | ${n('api')} / ${n('db')} / ${n('operator')} / ${n('manual')} / ${n('local')} | ${t.data.join(', ')} | ${t.approval ? '**Yes**' : 'Run authorization'} |`);
  }
  const reqs = new Map();
  for (const t of MATRIX) for (const q of t.requirement) reqs.set(q, [...(reqs.get(q) ?? []), t.id]);
  out.push('', '## By requirement', '', '| Requirement | Tests |\n|---|---|');
  for (const [q, ids] of [...reqs].sort(([a], [b]) => a.localeCompare(b))) out.push(`| ${esc(q)} | ${ids.join(', ')} |`);
  const checks = MATRIX.flatMap((t) => t.checks);
  const k = (x) => checks.filter((c) => c.kind === x).length;
  out.push('', '## Totals', '', `${MATRIX.length} tests and ${checks.length} checks: ${k('api')} api, ${k('db')} db, ${k('operator')} operator, ${k('manual')} manual, ${k('local')} local.`, '');
  return out.join('\n');
}
