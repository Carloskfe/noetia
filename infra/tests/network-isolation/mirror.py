#!/usr/bin/env python3
"""
NEM-017 — build a LOCAL test stack that mirrors the real compose files.

Reads the resolved `docker compose config --format json` of a real compose file
and writes a harness compose file that keeps, for every service, exactly the
real networks and Traefik labels, but replaces the application with a tiny
identity responder (HTTP on 3000/4000/5000/5432/6379/7700/9000 answering
"<env>-<service>"). TLS is dropped locally: `*.tls.certresolver` labels are
removed and the websecure entrypoint is plain HTTP.

External network names get a prefix that PRESERVES their sort order relative to
the project networks (Docker DNS prefers networks in name order), e.g.
"proxy" -> "<prefix>proxy", project "noetia" -> "<prefix>noetia".

Usage: mirror.py <config.json> <env-label> <prefix> <out.yml> [--traefik]
Local testing only — never run against the server.
"""
import json
import sys

RESPONDER = (
    "const h=require('http');for(const p of [3000,4000,5000,5432,6379,7700,9000])"
    "h.createServer((q,r)=>r.end(process.env.WHO)).listen(p)"
)


def esc(v: str) -> str:
    # `docker compose config` already escapes "$" as "$$"; normalise, then
    # escape exactly once for the generated compose file.
    return v.replace('$$', '$').replace('$', '$$')


def main() -> None:
    cfg_path, env, prefix, out = sys.argv[1:5]
    traefik = '--traefik' in sys.argv
    cfg = json.load(open(cfg_path))
    nets = cfg.get('networks', {})
    lines = ['# GENERATED by infra/tests/network-isolation/mirror.py — local test only', 'services:']
    for name, svc in cfg['services'].items():
        svc_nets = list((svc.get('networks') or {}).keys())
        lines.append(f'  {name}:')
        if traefik:
            lines += [
                '    image: traefik:v2.11',
                f'    container_name: {prefix}traefik',
                '    command:',
                '      - --providers.docker=true',
                '      - --providers.docker.exposedbydefault=false',
                f'      - --providers.docker.network={prefix}proxy',
                '      - --entrypoints.web.address=:80',
                '      - --entrypoints.websecure.address=:443',
                '      - --log.level=ERROR',
                '    ports: ["127.0.0.1:18080:80", "127.0.0.1:18443:443"]',
                '    volumes: ["/var/run/docker.sock:/var/run/docker.sock:ro"]',
            ]
        else:
            lines += [
                '    image: node:20-alpine',
                f'    command: ["node", "-e", {json.dumps(RESPONDER)}]',
                f'    environment: {{ WHO: "{env}-{name}" }}',
            ]
            labels = {k: v for k, v in (svc.get('labels') or {}).items()
                      if k.startswith('traefik.') and not k.endswith('.tls.certresolver')}
            for k, v in list(labels.items()):
                if k == 'traefik.docker.network':
                    labels[k] = prefix + v
            if labels:
                lines.append('    labels:')
                for k, v in sorted(labels.items()):
                    lines.append(f'      - {json.dumps(k + "=" + esc(v))}')
        lines.append(f'    networks: [{", ".join(svc_nets)}]')
    lines.append('networks:')
    for key, n in nets.items():
        if n.get('external'):
            lines.append(f'  {key}: {{ external: true, name: {prefix}{n.get("name", key)} }}')
        else:
            lines.append(f'  {key}: {{ driver: bridge }}')
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
